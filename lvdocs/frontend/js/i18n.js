// ==== Текущий язык ====
function getLang() {
    return localStorage.getItem('lvdocs_lang') || 'ru';
}

// ==== Перевод по ключу ====
function t(key) {
    const lang = getLang();
    return (TRANSLATIONS[lang] && TRANSLATIONS[lang][key]) || TRANSLATIONS.ru[key] || key;
}

// ==== Применить перевод ко всей странице ====
function applyTranslations() {
    const lang = getLang();
    document.documentElement.lang = lang;

    document.querySelectorAll('[data-i18n]').forEach(el => {
        el.innerHTML = t(el.getAttribute('data-i18n'));
    });

    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        el.placeholder = t(el.getAttribute('data-i18n-placeholder'));
    });

    // Подсветка активной кнопки
    document.querySelectorAll('.lang-btn').forEach(btn => {
        const on = btn.getAttribute('data-lang') === lang;
        btn.classList.toggle('active', on);
        btn.setAttribute('aria-pressed', on ? 'true' : 'false');
    });
}

// ==== Сменить язык ====
function setLanguage(lang) {
    localStorage.setItem('lvdocs_lang', lang);
    applyTranslations();
    document.dispatchEvent(new CustomEvent('langchange', { detail: lang }));
}

// Один обработчик на все страницы — onclick в кнопках не нужен
document.addEventListener('click', (e) => {
    const btn = e.target.closest('.lang-btn');
    if (btn && btn.dataset.lang) setLanguage(btn.dataset.lang);
});

document.addEventListener('DOMContentLoaded', applyTranslations);
